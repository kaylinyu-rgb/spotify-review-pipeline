"""Generate docs/RESULTS.md from saved outputs only (no model calls), so README numbers are never hand-copied."""
from __future__ import annotations

import csv
import json
from pathlib import Path

from .config import ROOT
from .records import read_jsonl
from .store import Store


def _j(p):
    p = Path(p)
    return json.loads(p.read_text()) if p.exists() else None


def _csv(p):
    p = Path(p)
    if not p.exists():
        return []
    with p.open(encoding="utf-8", newline="") as f:
        return list(csv.DictReader(f))


def report(run_dir: Path, out: Path | None = None):
    out = out or ROOT / "docs" / "RESULTS.md"
    rs = _j(run_dir / "run_summary.json") or {}
    ing = _j(run_dir / "ingestion_report.json") or {}
    ver = _j(run_dir / "verification_report.json") or {}
    gold = _j(ROOT / "evals" / "golden_results.json")
    sysr = _j(ROOT / "evals" / "system_tests_report.json") or {}
    cost = _j(ROOT / "cost" / "report.json")
    memo = _j(run_dir / "memo.json") or {}
    val = _j(run_dir / "memo_validation.json") or {}
    rank = _csv(run_dir / "ranking.csv")
    issues = {i["issue_id"]: i for i in (_j(run_dir / "issues.json") or [])}
    recs = {r["review_id"]: r for r in read_jsonl(run_dir / "enriched.jsonl")}
    db = Store(run_dir / "state.sqlite").db
    rel = lambda p: "../" + str(Path(p).relative_to(ROOT))
    L = [f"# Results — run `{run_dir.name}`", "",
         "_Generated by `python -m pipeline report --run " + run_dir.name + "` from saved outputs (no model calls)._", "",
         "## Coverage (accounted-for rows vs completed classifications)", "",
         "| measure | value |", "|---|---|",
         f"| input | `{rs.get('input', {}).get('name')}` sha256 `{rs.get('input', {}).get('sha256')}` |",
         f"| full course file? | {rs.get('is_full_course_file')} |",
         f"| source rows accounted for | {rs.get('records', 0):,} |",
         f"| completed classifications | {rs.get('completed', 0):,} |",
         f"| quarantined | {rs.get('quarantined', 0):,} — {json.dumps(rs.get('quarantine_reasons', {}))} |",
         f"| nonempty rows still not classified | {sum(v for k, v in rs.get('quarantine_reasons', {}).items() if k != 'empty_review_text'):,} |",
         f"| distinct nonempty texts sent to the model | {ing.get('distinct_nonempty_texts', 0):,} |",
         f"| rows labeled by exact-text cache reuse | {rs.get('cache_reuse_rows', 0):,} |",
         f"| duplicate IDs / missing app_version | {ing.get('duplicate_review_ids')} / {ing.get('missing_app_version', 0):,} |",
         f"| label_config | `{rs.get('label_config')}` |", ""]
    L += ["## Calls, usage and cost (actual, from the call log)", "", "| role | calls | failed | input tok | cached in | output tok | USD | unknown-usage calls |",
          "|---|---|---|---|---|---|---|---|"]
    for role, v in (rs.get("calls_by_role") or {}).items():
        L.append(f"| {role} | {v['calls']:,} | {v['failed'] or 0:,} | {v['input_tokens'] or 0:,} | {v['cached'] or 0:,} | {v['output_tokens'] or 0:,} | "
                 f"{(v['cost_usd'] or 0):.4f} | {v['usage_unknown_calls'] or 0} |")
    total = rs.get("total_cost_usd_known") or 0
    L += ["", f"**Known API spend: ${total:.4f}** (${total / max(1, rs.get('records', 1)) * 100000:.2f} per 100k rows; course cap $10/100k). "
          "Prices: `cost/rates.csv` (dated). Jev usage is logged; its price is unknown unless filled in, and is then shown separately.", ""]
    sess = rs.get("enrich_sessions") or []
    L += ["## Enrichment sessions (interruption → resume evidence)", "", "| session | phase | stop reason | +texts | calls | failed | wall s | USD |",
          "|---|---|---|---|---|---|---|---|"]
    for s in sess:
        L.append(f"| `{s.get('session_id')}` | {s.get('phase')} | {s.get('stop_reason')} | {s.get('completed_texts', 0):,} | {s.get('calls', 0):,} | "
                 f"{s.get('failed_calls', 0):,} | {s.get('wall_seconds')} | {s.get('spent', 0):.4f} |")
    L += ["", f"checkpoint_before: {rs.get('checkpoint_before_ids', 0):,} completed IDs → checkpoint_after: {rs.get('checkpoint_after_ids', 0):,}. "
          "Resume-phase calls never include checkpoint_before IDs (checked by `tools/check_submission.py`).", ""]
    L += ["## Independent verification (declared random sample)", "",
          f"Verifier `{ver.get('verifier')}`; rule: {ver.get('declared_sample', {}).get('rule')} with rate {ver.get('declared_sample', {}).get('rate')}. "
          f"Verified {ver.get('verified')} · topic agreement {ver.get('topic_agreement')} · intent {ver.get('intent_agreement')} · "
          f"severity exact {ver.get('severity_exact')} (MAE {ver.get('severity_mae')}) · disagreements {ver.get('disagreements')} "
          f"([list]({rel(run_dir / 'verify_disagreements.csv')})).", ""]
    if gold:
        a = gold["agreement"]
        L += ["## Golden 50 (human labels)", "", f"Topic {a['topic_exact']} (accepting alternatives {a['topic_accepting_alternatives']}) · intent {a['intent']} · "
              f"severity exact {a['severity_exact']} · severity MAE {gold['severity_mae']} · sentiment MAE {gold['sentiment_mae']} · "
              f"quote substring {gold['quote_exact_substring_rate']} · topic macro-F1 {gold['macro_f1']['topic']} · ambiguous {gold['ambiguous_cases']}. "
              "Details: [golden_report.md](../evals/golden_report.md).", ""]
    else:
        L += ["## Golden 50 (human labels)", "", "_Not evaluated yet — run `python evals/golden_eval.py --run runs/<id>`._", ""]
    if sysr:
        L += ["## System tests (actual outcomes)", "", "See [system_tests_report.md](../evals/system_tests_report.md): " +
              ", ".join(sysr.keys()) + ".", ""]
    if cost:
        c = cost["measured"]["cold"]; w = cost["measured"]["warm"]; b = cost["projection"]["scenarios"]["base"]["with_exact_text_reuse"]
        L += ["## 100-review pilot (measured) and projection", "", f"Cold ${c['api_usd']:.6f} in {c['wall_seconds']}s; warm ${w['api_usd']:.6f} in {w['wall_seconds']}s "
              f"with {w['stages'].get('enrich', {}).get('requests', 0)} enrichment calls. Base full-run projection ${b['total_api_usd']:.2f}. "
              "[cost/report.md](../cost/report.md)", ""]
    L += ["## Baseline ranking (top 10)", "", "| rank | issue | title | complaints | severity sum | mean | score |", "|---|---|---|---|---|---|---|"]
    for r in rank[:10]:
        L.append(f"| {r['rank']} | `{r['issue_id']}` | {issues.get(r['issue_id'], {}).get('title', '')} | {int(r['complaint_count']):,} | "
                 f"{int(r['severity_sum']):,} | {r['mean_severity']} | {int(r['priority_score']):,} |")
    L += ["", f"Recompute without a model: `python -m pipeline rerank --grading {run_dir.relative_to(ROOT)}/grading --check`.", ""]
    # one real review traced end to end
    cited = [rid for a in memo.get("actions", []) for rid in a.get("review_ids", [])]
    if cited and cited[0] in recs:
        r = recs[cited[0]]
        src = db.execute("SELECT review_text, review_rating, review_timestamp FROM source WHERE review_id=?", (r["review_id"],)).fetchone()
        call = db.execute("SELECT request_id, model, phase, input_tokens, output_tokens FROM calls WHERE request_id=?", (r.get("x_request_id"),)).fetchone()
        v = db.execute("SELECT * FROM verify WHERE review_id=?", (r["review_id"],)).fetchone()
        rk = next((x for x in rank if x["issue_id"] == r.get("x_label")), {})
        claims = [c for c in _csv(run_dir / "claims.csv") if c["issue_id"] == r.get("x_label")]
        L += ["## One real review, traced", "",
              f"1. **Source** `{r['review_id']}` ({src['review_timestamp']}, {src['review_rating']}★ metadata only): “{src['review_text'][:300]}”",
              f"2. **Enrichment** request `{call['request_id'] if call else r.get('x_request_id')}` ({call['model'] if call else ''}, phase {call['phase'] if call else ''}): "
              f"`{r.get('x_label')}`, {r['intent']}, severity {r['severity']}, sentiment {r['sentiment']}, quote “{r['evidence_quote']}” ({r.get('x_quote_source')}), "
              f"entities {r['entities']}, needs_review {r['needs_review']}.",
              f"3. **Verification**: " + (f"re-labeled blind as {v['topic']}/{v['intent']}/{v['severity']}." if v else "not in the declared 1% sample."),
              f"4. **Issue membership**: `{r.get('x_label')}` (membership.csv).",
              f"5. **Ranking**: rank {rk.get('rank')} — {rk.get('complaint_count')} complaints × mean {rk.get('mean_severity')} = {rk.get('priority_score')}.",
              f"6. **Memo claims**: " + ", ".join(f"{c['claim_id']} {c['metric']}={c['value']}" for c in claims) + "; quoted in memo.md.", ""]
    hard = db.execute("SELECT text_hash, reason, attempts, detail FROM quarantine LIMIT 1").fetchone()
    if hard:
        t = db.execute("SELECT rep_id, rep_text FROM texts WHERE text_hash=?", (hard["text_hash"],)).fetchone()
        L += ["## A failed case and its handling", "", f"`{t['rep_id']}`: “{t['rep_text'][:200]}” → quarantined `{hard['reason']}` after "
              f"{hard['attempts']} attempts (last error `{hard['detail']}`). It is excluded from all counts and listed in quarantine.jsonl.", ""]
    else:
        nr = next((r for r in recs.values() if r.get("needs_review") and r["status"] == "completed" and "cache_source_id" not in r), None)
        if nr:
            L += ["## An ambiguous case and its handling", "", f"`{nr['review_id']}`: quote “{nr['evidence_quote']}” → `{nr.get('x_label')}`/{nr['intent']}/sev {nr['severity']}, "
                  f"flagged needs_review ({nr.get('x_review_reason')}). Kept as a completed classification, counted normally, and surfaced in the dashboard filter.", ""]
    L += ["## Memo", "", f"Priority: **{memo.get('priority_area')}** — {memo.get('headline')} Code validation: {'PASS' if val.get('passed') else 'FAIL ' + str(val.get('errors'))}. "
          f"Full memo: [{run_dir.name}/memo.md]({rel(run_dir / 'memo.md')}).", ""]
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(L), encoding="utf-8")
    print(f"[report] wrote {out}")
